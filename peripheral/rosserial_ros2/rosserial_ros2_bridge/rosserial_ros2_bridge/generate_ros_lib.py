@dataclass
class Field:
    type: str
    name: str
    array: bool = False
    array_len: int | None = None


@dataclass
class Constant:
    type: str
    name: str
    value: str


def strip_comment(line):
    return line.split("#", 1)[0].strip()


def parse_array(type_name):
    match = re.match(r"(.+)\[(\d*)\]$", type_name)
    if not match:
        return type_name, False, None
    base, length = match.groups()
    return base, True, int(length) if length else None


def normalize_type(type_name, current_package):
    if type_name in BUILTINS or type_name in ("time", "duration"):
        return type_name
    if type_name in ("builtin_interfaces/Time", "builtin_interfaces/msg/Time"):
        return "time"
    if type_name in ("builtin_interfaces/Duration", "builtin_interfaces/msg/Duration"):
        return "duration"
    parts = type_name.split("/")
    if len(parts) == 1:
        return f"{current_package}/{type_name}"
    if len(parts) == 3 and parts[1] in ("msg", "srv"):
        return f"{parts[0]}/{parts[2]}"
    return type_name


def parse_fields(text, current_package):
    fields = []
    for raw_line in text.splitlines():
        line = strip_comment(raw_line)
        if not line or "=" in line:
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        raw_type, name = parts[:2]
        base_type, array, array_len = parse_array(raw_type)
        fields.append(Field(normalize_type(base_type, current_package), name, array, array_len))
    return fields


def parse_constants(text, current_package):
    constants = []
    for raw_line in text.splitlines():
        line = strip_comment(raw_line)
        if not line or "=" not in line:
            continue
        left, value = line.split("=", 1)
        parts = left.split()
        if len(parts) < 2:
            continue
        raw_type, name = parts[:2]
        constants.append(Constant(normalize_type(raw_type, current_package), name, value.strip()))
    return constants


def rosserial_header_fields():
    return [
        Field("uint32", "seq"),
        Field("time", "stamp"),
        Field("string", "frame_id"),
    ]


def schema_field(field):
    return {
        "name": field.name,
        "type": field.type,
        "array": field.array,
        "array_len": field.array_len,
    }


def schema_md5(fields):
    text = "\n".join(
        f"{field.type}{'[]' if field.array and field.array_len is None else '[' + str(field.array_len) + ']' if field.array else ''} {field.name}"
        for field in fields
    )
    return hashlib.md5(text.encode("utf-8")).hexdigest()


def type_suffix(field):
    if not field.array:
        return ""
    if field.array_len is None:
        return "[]"
    return f"[{field.array_len}]"


def ros1_field_type_text(field, message_specs, md5_cache):
    if field.type in BUILTINS or field.type in ("time", "duration"):
        return f"{field.type}{type_suffix(field)}"
    if field.type not in message_specs:
        raise RuntimeError(
            f"Missing message definition for {field.type}. "
            "Add the package that defines it with --packages or --package-paths."
        )
    return f"{ros1_message_md5(field.type, message_specs, md5_cache)}{type_suffix(field)}"


def ros1_constant_text(constant):
    return f"{constant.type} {constant.name}={constant.value}"


def ros1_message_text(type_name, message_specs, md5_cache):
    if type_name not in message_specs:
        raise RuntimeError(
            f"Missing message definition for {type_name}. "
            "Add the package that defines it with --packages or --package-paths."
        )
    spec = message_specs[type_name]
    lines = [ros1_constant_text(constant) for constant in spec["constants"]]
    lines.extend(
        f"{ros1_field_type_text(field, message_specs, md5_cache)} {field.name}"
        for field in spec["fields"]
    )
    return "\n".join(lines)


def ros1_message_md5(type_name, message_specs, md5_cache):
    if type_name in md5_cache:
        return md5_cache[type_name]
    text = ros1_message_text(type_name, message_specs, md5_cache)
    md5_cache[type_name] = hashlib.md5(text.encode("utf-8")).hexdigest()
    return md5_cache[type_name]


def ros1_service_md5(request_fields, response_fields, message_specs, md5_cache):
    request = "\n".join(
        f"{ros1_field_type_text(field, message_specs, md5_cache)} {field.name}"
        for field in request_fields
    )
    response = "\n".join(
        f"{ros1_field_type_text(field, message_specs, md5_cache)} {field.name}"
        for field in response_fields
    )
    return hashlib.md5((request + response).encode("utf-8")).hexdigest()


def cpp_type(field):
    base_type = cpp_base_type(field.type)
    if field.array:
        if field.array_len is None:
            return f"uint32_t {field.name}_length;\n  {base_type} * {field.name};"
        return f"{base_type} {field.name}[{field.array_len}];"
    return f"{base_type} {field.name};"


def cpp_base_type(type_name):
    if type_name in ("time", "duration"):
        return "ros::Time" if type_name == "time" else "ros::Duration"
    if type_name in BUILTINS:
        return BUILTINS[type_name]
    package, name = type_name.split("/", 1)
    return f"{package}::{name}"


def safe_identifier(value):
    return re.sub(r"\W+", "_", value).strip("_") or "field"


def include_for_type(type_name):
    if type_name in BUILTINS:
        return None
    if type_name == "time":
        return "ros/time.h"
    if type_name == "duration":
        return "ros/duration.h"
    package, name = type_name.split("/", 1)
    return f"{package}/{name}.h"


def serialize_scalar(field):
    name = field.name
    type_name = field.type
    if type_name == "string":
        return (
            f"uint32_t {name}_length = strlen(this->{name});\n"
            f"    ros::Msg::varToArr(outbuffer + offset, {name}_length);\n"
            f"    offset += 4;\n"
            f"    memcpy(outbuffer + offset, this->{name}, {name}_length);\n"
            f"    offset += {name}_length;"
        )
    if type_name == "time":
        return (
            f"ros::Msg::varToArr(outbuffer + offset, this->{name}.sec);\n"
            f"    offset += 4;\n"
            f"    ros::Msg::varToArr(outbuffer + offset, this->{name}.nsec);\n"
            f"    offset += 4;"
        )
    if type_name == "duration":
        return (
            f"ros::Msg::varToArr(outbuffer + offset, this->{name}.sec);\n"
            f"    offset += 4;\n"
            f"    ros::Msg::varToArr(outbuffer + offset, this->{name}.nsec);\n"
            f"    offset += 4;"
        )
    if type_name in CPP_SERIALIZE:
        return CPP_SERIALIZE[type_name][0].format(name=name)
    return f"offset += this->{name}.serialize(outbuffer + offset);"


def serialized_length_scalar(field):
    name = field.name
    type_name = field.type
    if type_name == "string":
        return f"offset += 4 + strlen(this->{name});"
    if type_name in ("time", "duration"):
        return "offset += 8;"
    fixed_sizes = {
        "bool": 1,
        "byte": 1,
        "char": 1,
        "int8": 1,
        "uint8": 1,
        "int16": 2,
        "uint16": 2,
        "int32": 4,
        "uint32": 4,
        "int64": 8,
        "uint64": 8,
        "float32": 4,
        "float64": 8,
    }
    if type_name in fixed_sizes:
        return f"offset += {fixed_sizes[type_name]};"
    return f"offset += this->{name}.serializedLength();"


def deserialize_scalar(field):
    return deserialize_scalar_expr(field.type, f"this->{field.name}", safe_identifier(field.name))


def deserialize_scalar_expr(type_name, target, local_name):
    if type_name == "string":
        return (
            f"uint32_t {local_name}_length;\n"
            f"    ros::Msg::arrToVar({local_name}_length, inbuffer + offset);\n"
            f"    offset += 4;\n"
            f"    if ({local_name}_length == 0) {{\n"
            f"      {target} = (char *)\"\";\n"
            f"    }} else {{\n"
            f"      for (uint32_t k = offset; k < offset + {local_name}_length; ++k) {{\n"
            f"        inbuffer[k - 1] = inbuffer[k];\n"
            f"      }}\n"
            f"      inbuffer[offset + {local_name}_length - 1] = 0;\n"
            f"      {target} = (char *)(inbuffer + offset - 1);\n"
            f"    }}\n"
            f"    offset += {local_name}_length;"
        )
    if type_name in ("time", "duration"):
        return (
            f"ros::Msg::arrToVar({target}.sec, inbuffer + offset);\n"
            f"    offset += 4;\n"
            f"    ros::Msg::arrToVar({target}.nsec, inbuffer + offset);\n"
            f"    offset += 4;"
        )
    if type_name in CPP_DESERIALIZE:
        code = CPP_DESERIALIZE[type_name][0].format(name=local_name)
        return code.replace(f"this->{local_name}", target)
    return f"offset += {target}.deserialize(inbuffer + offset);"


def serialize_field(field):
    if not field.array:
        return serialize_scalar(field)
    scalar = Field(field.type, "item")
    source = f"this->{field.name}[i]"
    body = serialize_scalar(scalar).replace("this->item", source).replace("item_length", f"{field.name}_item_length")
    prefix = ""
    if field.array_len is None:
        prefix = f"ros::Msg::varToArr(outbuffer + offset, this->{field.name}_length);\n    offset += 4;\n    "
        length_expr = f"this->{field.name}_length"
    else:
        length_expr = str(field.array_len)
    return prefix + f"for (uint32_t i = 0; i < {length_expr}; ++i) {{\n      " + body.replace("\n    ", "\n      ") + "\n    }"


def serialized_length_field(field):
    if not field.array:
        return serialized_length_scalar(field)
    scalar = Field(field.type, "item")
    source = f"this->{field.name}[i]"
    body = serialized_length_scalar(scalar).replace("this->item", source)
    prefix = ""
    if field.array_len is None:
        prefix = "offset += 4;\n    "
        length_expr = f"this->{field.name}_length"
    else:
        length_expr = str(field.array_len)
    return prefix + f"for (uint32_t i = 0; i < {length_expr}; ++i) {{\n      " + body.replace("\n    ", "\n      ") + "\n    }"


def deserialize_field(field):
    if not field.array:
        return deserialize_scalar(field)
    local_name = safe_identifier(field.name)
    body = deserialize_scalar_expr(field.type, f"this->{field.name}[i]", f"{local_name}_item").replace("\n    ", "\n      ")
    if field.array_len is None:
        base_type = cpp_base_type(field.type)
        return (
            f"uint32_t {local_name}_lengthT;\n"
            f"    ros::Msg::arrToVar({local_name}_lengthT, inbuffer + offset);\n"
            f"    offset += 4;\n"
            f"    if ({local_name}_lengthT > this->{field.name}_length) {{\n"
            f"      this->{field.name} = ({base_type} *)realloc(this->{field.name}, {local_name}_lengthT * sizeof({base_type}));\n"
            f"    }}\n"
            f"    this->{field.name}_length = {local_name}_lengthT;\n"
            f"    for (uint32_t i = 0; i < this->{field.name}_length; ++i) {{\n"
            f"      {body}\n"
            f"    }}"
        )
    return f"for (uint32_t i = 0; i < {field.array_len}; ++i) {{\n      {body}\n    }}"


def constructor_default(field):
    if field.array:
        if field.array_len is None:
            return [f"{field.name}_length(0)", f"{field.name}(nullptr)"]
        return []
    if field.type == "string":
        return [f"{field.name}((char *)\"\")"]
    if field.type in BUILTINS:
        return [f"{field.name}(0)"]
    return [f"{field.name}()"]


def render_constants(constants):
    lines = []
    for constant in constants:
        if constant.type in ("byte", "char", "int8", "uint8", "int16", "uint16", "int32", "uint32"):
            lines.append(f"enum {{ {constant.name} = {constant.value} }};")
        elif constant.type == "bool":
            lines.append(f"static const bool {constant.name} = {'true' if constant.value.lower() in ('true', '1') else 'false'};")
        elif constant.type in ("float32", "float64"):
            lines.append(f"static constexpr float {constant.name} = {constant.value};")
        elif constant.type == "string":
            lines.append(f"static constexpr const char * {constant.name} = \"{constant.value}\";")
    return "\n  ".join(lines)


def render_message_header(package, name, fields, md5, constants=None):
    constants = constants or []
    guard = f"_ROS_{package}_{name}_h"
    includes = {"stdint.h", "string.h", "ros/msg.h"}
    for field in fields:
        if field.array and field.array_len is None:
            includes.add("stdlib.h")
        inc = include_for_type(field.type)
        if inc:
            includes.add(inc)
    include_lines = "\n".join(
        f"#include <{inc}>" if inc.endswith(".h") and "/" not in inc else f"#include \"{inc}\""
        for inc in sorted(includes)
    )
    constants_body = render_constants(constants)
    constants_block = f"  {constants_body}\n\n" if constants_body else ""
    declarations = "\n  ".join(cpp_type(field) for field in fields)
    defaults = []
    for field in fields:
        defaults.extend(constructor_default(field))
    constructor = f"\n  {name}() : {', '.join(defaults)} {{}}" if defaults else ""
    serialize_body = "\n    ".join(serialize_field(field) for field in fields) or "(void)outbuffer;"
    length_body = "\n    ".join(serialized_length_field(field) for field in fields)
    deserialize_body = "\n    ".join(deserialize_field(field) for field in fields) or "(void)inbuffer;"
    return f"""// {GENERATED_MARKER}
#ifndef {guard}
#define {guard}

{include_lines}

namespace {package}
{{

class {name} : public ros::Msg
{{
public:
{constants_block}\
  {declarations}
{constructor}

  virtual int serialize(unsigned char *outbuffer) const override
  {{
    int offset = 0;
    {serialize_body}
    return offset;
  }}

  virtual int deserialize(unsigned char *inbuffer) override
  {{
    int offset = 0;
    {deserialize_body}
    return offset;
  }}

  virtual int serializedLength() const override
  {{
    int offset = 0;
    {length_body}
    return offset;
  }}

  virtual const char * getType() override {{ return "{package}/{name}"; }}
  virtual const char * getMD5() override {{ return "{md5}"; }}
}};

}}

#endif
"""


def render_service_class(package, class_name, rosserial_type, fields, md5):
    declarations = "\n  ".join(cpp_type(field) for field in fields)
    defaults = []
    for field in fields:
        defaults.extend(constructor_default(field))
    constructor = f"\n  {class_name}() : {', '.join(defaults)} {{}}" if defaults else ""
    serialize_body = "\n    ".join(serialize_field(field) for field in fields) or "(void)outbuffer;"
    length_body = "\n    ".join(serialized_length_field(field) for field in fields)
    deserialize_body = "\n    ".join(deserialize_field(field) for field in fields) or "(void)inbuffer;"
    return f"""class {class_name} : public ros::Msg
{{
public:
  {declarations}
{constructor}

  virtual int serialize(unsigned char *outbuffer) const override
  {{
    int offset = 0;
    {serialize_body}
    return offset;
  }}

  virtual int deserialize(unsigned char *inbuffer) override
  {{
    int offset = 0;
    {deserialize_body}
    return offset;
  }}

  virtual int serializedLength() const override
  {{
    int offset = 0;
    {length_body}
    return offset;
  }}

  virtual const char * getType() override {{ return "{rosserial_type}"; }}
  virtual const char * getMD5() override {{ return "{md5}"; }}
}};"""


def render_service_header(package, name, request_fields, response_fields, md5):
    guard = f"_ROS_{package}_{name}_h"
    includes = {"stdint.h", "string.h", "ros/msg.h"}
    for field in request_fields + response_fields:
        if field.array and field.array_len is None:
            includes.add("stdlib.h")
        inc = include_for_type(field.type)
        if inc:
            includes.add(inc)
    include_lines = "\n".join(
        f"#include <{inc}>" if inc.endswith(".h") and "/" not in inc else f"#include \"{inc}\""
        for inc in sorted(includes)
    )
    request = render_service_class(package, f"{name}Request", f"{package}/{name}", request_fields, md5)
    response = render_service_class(package, f"{name}Response", f"{package}/{name}", response_fields, md5)
    return f"""// {GENERATED_MARKER}
#ifndef {guard}
#define {guard}

{include_lines}

namespace {package}
{{

{request}

{response}

}}

#endif
"""


def has_interfaces(package_root):
    return any((package_root / kind).glob(f"*.{kind}") for kind in ("msg", "srv") if (package_root / kind).exists())


def read_package_name(package_root):
    package_xml = package_root / "package.xml"
    if not package_xml.exists():
        return package_root.name
    try:
        root = ET.fromstring(package_xml.read_text(encoding="utf-8"))
    except ET.ParseError as exc:
        raise RuntimeError(f"Cannot parse {package_xml}: {exc}") from exc
    name = root.findtext("name")
    if not name:
        raise RuntimeError(f"{package_xml} does not contain a <name> element")
    return name.strip()


def discover_source_packages(paths):
    packages = {}
    for raw_path in paths or []:
        path = Path(raw_path).expanduser().resolve()
        if not path.exists():
            raise RuntimeError(f"Interface source path does not exist: {path}")

        if (path / "package.xml").exists():
            candidates = [path]
        else:
            candidates = [package_xml.parent for package_xml in sorted(path.rglob("package.xml"))]

        for package_root in candidates:
            if not has_interfaces(package_root):
                continue
            package_name = read_package_name(package_root)
            packages[package_name] = package_root
    return packages


def dedupe_keep_order(items):
    result = []
    seen = set()
    for item in items:
        if item in seen:
            continue
        seen.add(item)
        result.append(item)
    return result


def build_package_index(packages, package_paths):
    source_packages = discover_source_packages(package_paths)
    all_packages = dedupe_keep_order(list(packages) + list(source_packages))
    package_index = dict(source_packages)

    for package in all_packages:
        if package in package_index:
            continue
        try:
            package_index[package] = Path(get_package_share_directory(package))
        except (PackageNotFoundError, OSError) as exc:
            raise RuntimeError(
                f"Cannot find ROS 2 interface package {package}. "
                "Install/source it in ROS 2, or pass its source directory with --package-paths."
            ) from exc

    return all_packages, package_index


def find_interface_files(package, kind, package_index):
    folder = package_index[package] / kind
    if not folder.exists():
        return []
    return sorted(folder.glob(f"*.{kind}"))


def write_file(path, text, overwrite, overwrite_generated=False):
    if path.exists() and not overwrite:
        if not overwrite_generated:
            return False
        existing = path.read_text(encoding="utf-8", errors="replace")
        if GENERATED_MARKER not in existing:
            return False
        path.write_text(text, encoding="utf-8")
        return True
    if path.exists() and overwrite_generated and not overwrite:
        existing = path.read_text(encoding="utf-8", errors="replace")
        if GENERATED_MARKER not in existing:
            return False
    if path.exists() and not overwrite and not overwrite_generated:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def collect_message_specs(packages, package_index):
    specs = {}
    for package in packages:
        for msg_file in find_interface_files(package, "msg", package_index):
            name = msg_file.stem
            text = msg_file.read_text(encoding="utf-8")
            if package == "std_msgs" and name == "Header":
                fields = rosserial_header_fields()
                constants = []
            else:
                fields = parse_fields(text, package)
                constants = parse_constants(text, package)
            specs[f"{package}/{name}"] = {
                "package": package,
                "name": name,
                "fields": fields,
                "constants": constants,
                "text": text,
            }
    return specs


